// 백현이 대사를 ‘나에게 말하는 반말’로 보여주기 (화면 표시용 · 저장된 데이터는 그대로)
// 라이브에서 팬들에게 하는 존댓말(여러분, ~요, ~습니다)을 1:1 대화 말투로 바꿔요. 규칙 기반이라 완벽하지 않을 수 있어요.
const WORD = [
  [/여러분들?/g, '너'], [/다들\s/g, '너 '], [/저희/g, '우리'], [/저는/g, '나는'], [/저도/g, '나도'], [/제가/g, '내가'], [/저한테/g, '나한테'], [/저를/g, '나를'], [/저랑/g, '나랑'], [/저의/g, '내'],
  [/(^|\s)제\s/g, '$1내 '], [/^네([,.!\s])/, '응$1'],
  [/안녕하세요/g, '안녕'], [/감사합니다|감사해요|고맙습니다/g, '고마워'], [/죄송합니다|죄송해요/g, '미안해'],
  [/말씀하세요/g, '말해'], [/주세요/g, '줘'], [/하세요/g, '해'], [/보세요/g, '봐'], [/가세요/g, '가'], [/오세요/g, '와'], [/드세요/g, '먹어'], [/주무세요/g, '자'], [/계세요/g, '있어'], [/마세요/g, '마'],
  [/드릴게요/g, '줄게'], [/드려요/g, '줄게'], [/드릴까요/g, '줄까'],
  [/입니다/g, '이야'], [/합니다/g, '해'], [/됩니다/g, '돼'], [/습니다/g, '어'], [/습니까/g, '어?'],
  [/이에요/g, '이야'], [/예요/g, '야'], [/세요(?=[\s.,!?~]|$)/g, '어'], [/(?<![필중수소])요(?=[\s.,!?~ㅋㅎ]|$)/g, '']
];
export function banmal(ko) {
  let s = String(ko || '');
  for (const [re, to] of WORD) s = s.replace(re, to);
  return s.replace(/\s{2,}/g, ' ').trim();
}
